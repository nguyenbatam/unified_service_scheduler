export type IconName = keyof typeof PATHS;

/**
 * A decorative icon in the current text colour, sized to the text. Always aria-hidden and textless,
 * so the label next to it stays the accessible name (and the element's textContent).
 */
export function Icon({ name, className }: { name: IconName; className?: string }) {
  return (
    <svg
      className={className ? `icon ${className}` : "icon"}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {PATHS[name]}
    </svg>
  );
}

const STATUS_ICON: Record<number, IconName> = {
  [Status.Confirmed]: "calendarCheck",
  [Status.CheckedIn]: "logIn",
  [Status.InProgress]: "wrench",
  [Status.Completed]: "checkCircle",
  [Status.Cancelled]: "xCircle",
  [Status.NoShow]: "userX",
};

/** The icon of an appointment status: shown with its colour, so the status reads without it. */
export function statusIcon(status: number): IconName {
  return STATUS_ICON[status] ?? "info";
}

const ROLE_ICON: Record<number, IconName> = {
  [Role.Admin]: "shield",
  [Role.Dispatcher]: "headset",
  [Role.Customer]: "user",
};

export function roleIcon(role: number): IconName {
  return ROLE_ICON[role] ?? "user";
}

const BAY_ICON: Record<number, IconName> = {
  [Bay.Express]: "zap",
  [Bay.General]: "wrench",
  [Bay.Diagnostic]: "gauge",
  [Bay.Alignment]: "crosshair",
};

/** The icon of a bay type, shown next to its name so the kind of bay reads at a glance. */
export function bayIcon(bayType: number): IconName {
  return BAY_ICON[bayType] ?? "bay";
}

const SKILL_ICON: Record<number, IconName> = {
  [Skill.Lubrication]: "droplet",
  [Skill.Brakes]: "disc",
  [Skill.General]: "wrench",
};

/**
 * The icon of a skill; services show the one of the skill they need (the catalog is admin-edited,
 * so a new service gets a fitting icon without one being picked for it).
 */
export function skillIcon(skill: number): IconName {
  return SKILL_ICON[skill] ?? "wrench";
}

const REASON_ICON: Record<string, IconName> = {
  past: "clock",
  lead_time: "clock",
  beyond_horizon: "calendar",
  lunch_break: "coffee",
  vehicle_busy: "car",
  staging_full: "car",
  no_bay: "bay",
  no_technician: "hardHat",
  no_resources: "xCircle",
};

/** The icon of an unavailable slot's reason (a generic one for codes this build does not know). */
export function slotReasonIcon(reason: string | undefined): IconName {
  return (reason && REASON_ICON[reason]) || "xCircle";
}
